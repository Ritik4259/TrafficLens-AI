"""
SQLAlchemy model for Evidence-Grounded Traffic Incident Reports.
"""

from __future__ import annotations
from datetime import datetime, timezone
from typing import Any, Dict, Optional, TYPE_CHECKING
from sqlalchemy import Boolean, ForeignKey, Index, JSON, String, Text
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .base import Base, UTCDateTime

if TYPE_CHECKING:
    from .job import ProcessingJob


class IncidentReport(Base):
    """
    Represents an evidence-grounded incident report generated by the LangGraph agent
    for a completed ProcessingJob.
    """
    __tablename__ = "incident_reports"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, index=True)
    job_id: Mapped[str] = mapped_column(
        String(36),
        ForeignKey("processing_jobs.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    status: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default="COMPLETED",
        index=True,
    )
    created_at: Mapped[datetime] = mapped_column(
        UTCDateTime,
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
        index=True,
    )
    summary: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    report_data: Mapped[Dict[str, Any]] = mapped_column(JSON, nullable=False)
    validation_passed: Mapped[bool] = mapped_column(Boolean, default=True, nullable=False)
    validation_summary: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)
    error_message: Mapped[Optional[str]] = mapped_column(Text, nullable=True)

    # Relationships
    job: Mapped["ProcessingJob"] = relationship("ProcessingJob", back_populates="incident_reports")

    __table_args__ = (
        Index("ix_incident_reports_job_created", "job_id", "created_at"),
    )

    def __repr__(self) -> str:
        return f"<IncidentReport id={self.id} job_id={self.job_id} status={self.status}>"
