"""
FastAPI endpoints for Evidence-Grounded Traffic Incident Reports.

Exposes RESTful endpoints for triggering, querying, and retrieving historical
incident reports generated by the LangGraph incident agent.
"""

from __future__ import annotations
import asyncio
import logging
from typing import Dict, Optional
from fastapi import APIRouter, Depends, HTTPException, Query, status
from sqlalchemy.orm import Session

from backend.app.core.config import Settings
from backend.app.dependencies import get_app_settings, get_db_session
from backend.app.repositories.job_repository import SQLAlchemyJobRepository
from backend.app.schemas.incident_report import (
    IncidentReportHistoryResponseSchema,
    IncidentReportResponseSchema,
)
from backend.app.schemas.job import JobStatus
from backend.app.services.agent.service import IncidentReportService

logger = logging.getLogger("trafficlens.api.incident_reports")

router = APIRouter(tags=["Incident Reports"])

# Process-level asynchronous serialization lock for concurrent report generation requests.
#
# NOTE ON CONCURRENCY BOUNDARY:
# Process-local synchronization (asyncio.Lock) guarantees single-flight serialization within
# a single Python process / event loop (sufficient for the single-process MVP).
# However, process-local synchronization does NOT guarantee mutual exclusion across multiple
# worker processes (e.g., Uvicorn running with multiple workers: --workers 4) or horizontally
# scaled container replicas. For multi-process or multi-node production deployments, a distributed
# locking mechanism (e.g. Redis Redlock or database advisory locks) must be used.
_incident_report_async_locks: Dict[Optional[asyncio.AbstractEventLoop], asyncio.Lock] = {}


def get_incident_report_lock() -> asyncio.Lock:
    """
    Returns an asyncio.Lock tied to the current running event loop.
    Ensures coroutine-level serialization without blocking the OS thread or event loop.
    """
    try:
        loop = asyncio.get_running_loop()
    except RuntimeError:
        loop = None

    if loop not in _incident_report_async_locks:
        _incident_report_async_locks[loop] = asyncio.Lock()
    return _incident_report_async_locks[loop]


@router.post(
    "/jobs/{job_id}/incident-reports",
    response_model=IncidentReportResponseSchema,
    status_code=status.HTTP_201_CREATED,
    summary="Generate evidence-grounded incident report for a completed job",
)
@router.post(
    "/jobs/{job_id}/incident-report",
    response_model=IncidentReportResponseSchema,
    status_code=status.HTTP_201_CREATED,
    include_in_schema=False,
)
async def generate_incident_report(
    job_id: str,
    db: Session = Depends(get_db_session),
    settings: Settings = Depends(get_app_settings),
) -> IncidentReportResponseSchema:
    """
    Triggers the LangGraph incident agent to generate an evidence-grounded
    incident report for a COMPLETED processing job.
    """
    job_repo = SQLAlchemyJobRepository(db)
    job = job_repo.get_job_model(job_id)
    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Job '{job_id}' not found.",
        )

    if job.status in (JobStatus.QUEUED, JobStatus.PROCESSING):
        raise HTTPException(
            status_code=status.HTTP_409_CONFLICT,
            detail=f"Job '{job_id}' is currently {job.status.value}. Incident report can only run on COMPLETED jobs.",
        )

    if job.status == JobStatus.FAILED:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=f"Job '{job_id}' failed: {job.error_message or 'Pipeline error'}. Cannot generate incident report.",
        )

    lock = get_incident_report_lock()
    async with lock:
        service = IncidentReportService(db=db, settings=settings)
        report_response = await service.generate_incident_report(job_id)

    if report_response.status == "FAILED":
        err_lower = (report_response.error_message or "").lower()
        if "timed out" in err_lower or "timeout" in err_lower:
            raise HTTPException(
                status_code=status.HTTP_504_GATEWAY_TIMEOUT,
                detail=f"Incident report generation timed out: {report_response.error_message}",
            )
        if any(keyword in err_lower for keyword in ["provider", "502", "429", "connection"]):
            raise HTTPException(
                status_code=status.HTTP_502_BAD_GATEWAY,
                detail=f"LLM provider failure: {report_response.error_message}",
            )
        if "no cv telemetry" in err_lower:
            raise HTTPException(
                status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
                detail=f"Unprocessable entity: {report_response.error_message}",
            )
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Incident report generation failed: {report_response.error_message}",
        )

    return report_response


@router.get(
    "/jobs/{job_id}/incident-reports",
    response_model=IncidentReportHistoryResponseSchema,
    summary="List historical incident reports for a job",
)
def list_incident_reports_for_job(
    job_id: str,
    ascending: bool = Query(True, description="Sort order by creation timestamp"),
    db: Session = Depends(get_db_session),
    settings: Settings = Depends(get_app_settings),
) -> IncidentReportHistoryResponseSchema:
    """Returns the complete audit history of incident reports generated for a job."""
    job_repo = SQLAlchemyJobRepository(db)
    job = job_repo.get_job_model(job_id)
    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Job '{job_id}' not found.",
        )

    service = IncidentReportService(db=db, settings=settings)
    return service.list_reports_for_job(job_id=job_id, ascending=ascending)


@router.get(
    "/jobs/{job_id}/incident-report",
    response_model=IncidentReportResponseSchema,
    summary="Get latest incident report for a job",
)
def get_latest_incident_report_for_job(
    job_id: str,
    db: Session = Depends(get_db_session),
    settings: Settings = Depends(get_app_settings),
) -> IncidentReportResponseSchema:
    """Returns the most recent incident report generated for a job."""
    job_repo = SQLAlchemyJobRepository(db)
    job = job_repo.get_job_model(job_id)
    if not job:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Job '{job_id}' not found.",
        )

    service = IncidentReportService(db=db, settings=settings)
    report = service.get_latest_report_for_job(job_id)
    if not report:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"No incident report has been generated for job '{job_id}'.",
        )
    return report


@router.get(
    "/incident-reports/{report_id}",
    response_model=IncidentReportResponseSchema,
    summary="Get incident report by ID",
)
def get_incident_report_by_id(
    report_id: str,
    db: Session = Depends(get_db_session),
    settings: Settings = Depends(get_app_settings),
) -> IncidentReportResponseSchema:
    """Retrieves a specific incident report by its unique identifier."""
    service = IncidentReportService(db=db, settings=settings)
    report = service.get_report(report_id)
    if not report:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail=f"Incident report '{report_id}' not found.",
        )
    return report
